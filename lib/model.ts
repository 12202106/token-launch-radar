// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// early radar: pre-token protocols below the watchlist floor that pass the same cleanliness test the
// watchlist rule applies — not a bridge, not liquid staking or restaking, not a wrapped or staked
// product, not an exchange product and not a versioned pool. A protocol is pre-token when its index
// entry records no token (no market cap, no CoinGecko id, no symbol); the snapshot's live-token
// protocols are kept apart and shown with the market's own values, never mixed into the ranked board,
// and the pre-token protocols the board leaves out are listed, each with its reason, in the set-aside
// view instead of being silently dropped.
//
// Implied value follows only from the snapshot's own figures:
//
//   baseMultiple = the median market-cap-to-TVL ratio of the protocols in this snapshot whose token
//                  already trades (128 of them here), clamped to [0.05, 0.60]. The anchor is the
//                  market's own pricing of live protocols, recomputed from the snapshot on every run,
//                  never a number typed in by hand.
//   base       = tvl_usd x baseMultiple
//   growth     = clamp(change_7d, -40, 80) per cent
//   growthMult = 1 + (growth / 100) x 0.35
//   maturity   = 0.65 + min(age_days, 1460) / 1460 x 0.50   (age_days unknown: 365)
//   breadth    = 1 + min(chains - 1, 4) x 0.02             (a protocol on more chains reaches more users)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// TVL is the size of the protocol, growth is its momentum, age is how long it has run with no token
// (the best record of a track record without a launch), and breadth is how many chains it runs on.
// No protocol name is ever special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

